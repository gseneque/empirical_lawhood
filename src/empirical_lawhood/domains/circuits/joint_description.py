"""Finite information descriptions of prospectively driven RC systems.

The preparation begins before the decision boundary.  History observations are
therefore generated by forward evolution, never by looking at a response after
the selected action.  Reconstruction supplies a state estimate to the same
known linear physical law for every information arm.  These are comparisons of
constitutive *information*, not claims that a reduced arm has a smaller
numerical state-space implementation.
"""

