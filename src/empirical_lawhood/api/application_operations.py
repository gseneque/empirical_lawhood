def application_operations() -> tuple[ApplicationOperation, ...]:
    return OPERATIONS


def application_operation(operation_id: str) -> ApplicationOperation:
    for operation in OPERATIONS:
        if operation.operation_id == operation_id:
            return operation
    raise ApplicationError("UNSUPPORTED_OPERATION", "This installation has no handler for the selected operation.",
                           field="operation", category=ErrorCategory.CAPABILITY)
